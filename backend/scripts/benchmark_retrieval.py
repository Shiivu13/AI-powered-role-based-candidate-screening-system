"""Benchmark retrieval strategies on the ingested knowledge base.

Usage (from ``backend/``)::

    python -m scripts.benchmark_retrieval                    # all roles, strategy comparison
    python -m scripts.benchmark_retrieval --chunk-sizes 500 1000 1500   # + chunk-size ablation

Writes ``docs/benchmarks/retrieval.md`` and ``retrieval.json`` at the repo root.
See ``app/rag/evaluation.py`` for how the labelled set is built.
"""
from __future__ import annotations

import argparse
import json
import logging
import time
from pathlib import Path

from app.ai.catalog import BOOKS, ROLES
from app.config import get_settings
from app.rag.evaluation import Doc, EvalIndex, build_eval_set, chunk_size_ablation, evaluate, fit_text_only_lsa, standard_methods
from app.rag.loaders import load_document
from app.rag.vector_store import VectorStore

REPO_ROOT = Path(__file__).resolve().parents[2]
METRICS = ["hit@1", "hit@4", "precision@4", "mrr@10", "ndcg@10", "redundancy@4"]


def _table(rows: dict[str, dict], first_col: str, cols: list[str]) -> str:
    lines = [f"| {first_col} | " + " | ".join(cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for name, values in rows.items():
        lines.append(f"| {name} | " + " | ".join(str(values.get(c, "")) for c in cols) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--roles", nargs="*", choices=list(ROLES), default=list(ROLES))
    parser.add_argument("--max-queries", type=int, default=150)
    parser.add_argument("--chunk-sizes", nargs="*", type=int, default=[])
    parser.add_argument("--ablation-role", choices=list(ROLES), default="data_scientist")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "benchmarks")
    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING)

    report: dict = {"generated_at": time.strftime("%Y-%m-%d"), "roles": {}, "chunk_size_ablation": {}}
    md = ["# Retrieval benchmark", "",
          "Generated by `python -m scripts.benchmark_retrieval`. Queries are numbered section titles from the books; "
          "relevant chunks are the chunks of that section; the index is rebuilt from chunk text only, so titles cannot be matched "
          "through headers (the LSA space is also re-fitted on chunk bodies only). `redundancy@4` is the mean pairwise cosine similarity of the top-4 results (lower = more diverse context).", ""]

    for role_id in args.roles:
        stored = VectorStore(role_id).get_all()
        docs = [Doc(c.id, c.text, c.metadata["book_id"], c.metadata.get("section", "")) for c in stored]
        queries = build_eval_set(docs, max_queries=args.max_queries)
        if not queries:
            print(f"{role_id}: no evaluable sections, skipped")
            continue
        index = EvalIndex(docs, fit_text_only_lsa(docs))
        results = evaluate(index, queries, standard_methods(index))
        report["roles"][role_id] = {"queries": len(queries), "chunks": len(docs), "results": results}
        md += [f"## {ROLES[role_id].title}", "", f"{len(queries)} queries over {len(docs)} chunks.", "",
               _table(results, "strategy", METRICS), ""]
        print(f"\n{ROLES[role_id].title} ({len(queries)} queries)")
        print(_table(results, "strategy", METRICS))

    if args.chunk_sizes:
        role = ROLES[args.ablation_role]
        books_dir = get_settings().resolved_books_dir
        pages_by_book = {
            b: (BOOKS[b].title, load_document(books_dir / BOOKS[b].filename))
            for b in role.book_ids
            if (books_dir / BOOKS[b].filename).exists()
        }
        ablation = chunk_size_ablation(pages_by_book, args.chunk_sizes, max_queries=args.max_queries)
        report["chunk_size_ablation"] = {"role": args.ablation_role, "results": ablation}
        cols = ["chunks", "avg_chars", "queries", "hit@4", "precision@4", "mrr@10", "ndcg@10"]
        md += [f"## Chunk size ablation ({role.title}, hybrid retrieval with BM25 weight 0.5, 20% overlap, same queries for every size)", "",
               _table({f"{k} chars": v for k, v in ablation.items()}, "chunk size", cols), ""]
        print("\nChunk size ablation")
        print(_table({f"{k} chars": v for k, v in ablation.items()}, "chunk size", cols))

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "retrieval.json").write_text(json.dumps(report, indent=2))
    (args.out / "retrieval.md").write_text("\n".join(md))
    print(f"\nWrote {args.out / 'retrieval.md'}")


if __name__ == "__main__":
    main()
